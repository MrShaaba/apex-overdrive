export const VEHICLE_BY_ID: Record<string, VehicleSpec> = Object.fromEntries(VEHICLE_CATALOG.map((v) => [v.id, v]))

/** Ids of retired procedural cars → their licensed replacements (saves, career rewards, AI favourites). */
export const VEHICLE_ID_ALIASES: Record<string, string> = {
  'v8-roadster': 'dodge-charger',
  'grand-tourer': 'lamborghini-huracan-gt3',
  'modern-supercar': 'lamborghini-revuelto',
}

export function resolveVehicleId(id: string): string {
  return VEHICLE_ID_ALIASES[id] ?? id
}

export function getVehicleSpec(id: string): VehicleSpec {
  const spec = VEHICLE_BY_ID[resolveVehicleId(id)]
  if (!spec) {
    console.warn(`[Catalog] Unknown vehicle "${id}", falling back to ${VEHICLE_CATALOG[0].id}`)
    return VEHICLE_CATALOG[0]
  }
  return spec
}

