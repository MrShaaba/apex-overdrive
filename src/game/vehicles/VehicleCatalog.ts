export function resolveVehicleId(id: string): string {
  return VEHICLE_ID_ALIASES[id] ?? id
}

export function getVehicleSpec(id: string): VehicleSpec {
  const spec = VEHICLE_BY_ID[resolveVehicleId(id)]
  if (!spec) {
    console.warn(`[Catalog] Unknown vehicle "${id}", falling back to ${VEHICLE_CATALOG[0].id}`)
    return VEHICLE_CATALOG[0]
  }
  return spec
}

